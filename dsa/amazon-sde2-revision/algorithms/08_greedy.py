    # You are given a string s. We want to partition the string into as many parts as possible so that each letter appears in at most one part. For example, the string "ababcc" can be partitioned into ["abab", "cc"], but partitions such as ["aba", "bcc"] or ["ab", "ab", "cc"] are invalid. Note that the partition is done so that after concatenating all the parts in order, the resultant string should be s. Return a list of integers representing the size of these parts.
    # Example: s = "ababcbacadefegdehijhklij" → [9,7,8]
    # Constraints: 1 <= s.length <= 500, s consists of lowercase English letters
    # Time: O(n), Space: O(1)
    # -----------------------------------------------------------------------
    def partitionLabels(self, s: str) -> List[int]:
        # Step 1: Record the last occurrence of each character in s.
        lastIndex = {}
        for i, c in enumerate(s):
            lastIndex[c] = i
        res = []
        size, end = 0, 0
        # Step 2: Iterate through the string to determine partition boundaries.
        for i, c in enumerate(s):
            size += 1
            # Expand the boundary to include the last occurrence of character c.
            end = max(end, lastIndex[c])
            # If the current index reaches the end boundary, we close the partition.
            if i == end:
                res.append(size)
                # Reset partition size for the next segment.
                size = 0
        return res


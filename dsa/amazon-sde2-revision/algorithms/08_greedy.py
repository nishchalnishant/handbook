    # Example: clips = [[0,2],[4,6],[8,10],[1,9],[1,5],[5,9]], time = 10 → 3
    # Constraints: 1 <= clips.length <= 100, 0 <= starti <= endi <= 100, 1 <= time <= 100
    # Time: O(n log n), Space: O(1)
    # -----------------------------------------------------------------------
    def videoStitching(self, clips: List[List[int]], time: int) -> int:
        """Video Stitching (LC 1024): Sort clips by start time."""
        min_reach, max_reach, res = 0, 0, 0
        # Sort clips by start time to process them in chronological order.
        clips.sort()
        i = 0
        # Expand coverage until the target time is reached.
        while max_reach < time:
            # Check all clips that can start at or before the current coverage limit.
            while i < len(clips) and clips[i][0] <= min_reach:
                # Track the furthest right point we can reach.
                max_reach = max(max_reach, clips[i][1])
                i += 1
            # If our maximum reach has not advanced, we hit a gap we cannot bridge.
            if min_reach == max_reach:
                return -1
            # Advance our current coverage limit to the furthest reached point.
            min_reach = max_reach
            res += 1
        return res


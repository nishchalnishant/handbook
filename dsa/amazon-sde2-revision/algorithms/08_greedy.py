    # You are given an integer array nums. You are initially positioned at the array's first index, and each element in the array represents your maximum jump length at that position. Return true if you can reach the last index, or false otherwise.
    # Example: nums = [2,3,1,1,4] → true
    # Constraints: 1 <= nums.length <= 10^4, 0 <= nums[i] <= 10^5
    # Time: O(n), Space: O(1)
    # -----------------------------------------------------------------------
    def canJump(self, nums: List[int]) -> bool:
        # Initialize goal as the last index we need to reach.
        goal = len(nums) - 1
        # Work backwards from the second-to-last element to index 0.
        for i in range(len(nums) - 1, -1, -1):
            # If we can jump far enough from index i to reach or pass the goal:
            if i + nums[i] >= goal:
                # Update goal to index i, since any path reaching i can now reach the end.
                goal = i
        # If the goal successfully propagates back to index 0, return True.
        return True if goal == 0 else False


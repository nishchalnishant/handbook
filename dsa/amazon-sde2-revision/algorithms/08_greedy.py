    # You are given an integer array nums. You are initially positioned at the array's first index, and each element in the array represents your maximum jump length at that position. Return true if you can reach the last index, or false otherwise.
    # Example: nums = [2,3,1,1,4] → true
    # Constraints: 1 <= nums.length <= 10^4, 0 <= nums[i] <= 10^5, 0, Each element nums[i] represents the maximum length of a forward jump from index i. In other words,, if you are at index i, you can jump to any index (i + j) where:, 0 <= j <= nums[i] and, i + j < n, Return the minimum number of jumps to reach index n - 1. The test cases are generated such that you, can reach index n - 1, 1 <= nums.length <= 10^4, 0 <= nums[i] <= 1000, It's guaranteed that you can reach nums[n - 1]
    # Time: O(n), Space: O(1)
    # -----------------------------------------------------------------------
    def jump(self, nums: List[int]) -> int:
        res = 0
        # l and r represent the boundaries of the current BFS level (reach window).
        l = r = 0
        # Keep searching while the right boundary has not reached the last index.
        while r < len(nums) - 1:
            farthest = 0
            # Scan all indices in the current level to find the maximum reach.
            for i in range(l, r + 1):
                farthest = max(farthest, i + nums[i])
            # Next level starts immediately after the current right boundary.
            l = r + 1
            # Next level's right boundary is the farthest reachable index.
            r = farthest
            # Increment the jump count for the transition to the next level.
            res += 1
        return res


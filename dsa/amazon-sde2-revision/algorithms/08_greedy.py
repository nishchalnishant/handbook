    # 10. The Skyline Problem (L4) — Sweep line + heap with lazy deletion
    # A city's skyline is the outer contour of the silhouette formed by all the buildings in that city when viewed from a distance. Given the locations and heights of all the buildings, return the skyline formed by these buildings collectively.
    # Example: buildings = [[2,9,10],[3,7,15],[5,12,12],[15,20,10],[19,24,8]] → [[2,10],[3,15],[7,12],[12,0],[15,10],[20,8],[24,0]]
    # Constraints: 1 <= buildings.length <= 10^4
    # Time: O(n log n), Space: O(n)
    # -----------------------------------------------------------------------
    def getSkyline(self, buildings: List[List[int]]) -> List[List[int]]:
        # Events: (x, -h, end_x) for start event, (x, 0, 0) for end event.
        # negated height ensures starts are processed before ends at same x.
        events = []
        for l, r, h in buildings:
            events.append((l, -h, r))
            events.append((r, 0, 0))
        events.sort(key=lambda x: (x[0], x[1]))

        result = []
        # Max-heap storing (-height, end_x) elements.
        # Sentinel (0, float('inf')) ensures the heap is never empty.
        heap = [(0, float('inf'))]

        for x, neg_h, r in events:
            # Start event: push building height and its end position onto the heap.
            if neg_h < 0:
                heapq.heappush(heap, (neg_h, r))

            # Lazy deletion: remove buildings from the top of the heap if they have ended at or before x.
            while heap and heap[0][1] <= x:
                heapq.heappop(heap)

            # Get the current maximum height from the top of the heap.
            cur_h = -heap[0][0]
            
            # If the current max height changes, append the new coordinate to the skyline contour.
            if not result or result[-1][1] != cur_h:
                result.append([x, cur_h])
                
        return result


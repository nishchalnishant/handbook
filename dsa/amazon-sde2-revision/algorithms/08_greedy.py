    # There are n gas stations along a circular route, where the amount of gas at the i^th station is gas[i]. You have a car with an unlimited gas tank and it costs cost[i] of gas to travel from the i^th station to its next (i + 1)^th station. You begin the journey with an empty tank at one of the gas stations. Given two integer arrays gas and cost, return the starting gas station's index if you can travel around the circuit once in the clockwise direction, otherwise return -1. If there exists a solution, it is guaranteed to be unique.
    # Example: gas = [1,2,3,4,5], cost = [3,4,5,1,2] → 3
    # Constraints: n == gas.length == cost.length, 1 <= n <= 10^5, 0 <= gas[i], cost[i] <= 10^4, The input is generated such that the answer is unique
    # Time: O(n), Space: O(1)
    # -----------------------------------------------------------------------
    def canCompleteCircuit(self, gas: List[int], cost: List[int]) -> int:
        # Feasibility check: if total gas is less than total cost, no solution exists.
        if sum(gas) < sum(cost):
            return -1
        total = 0
        res = 0
        # Scan through each gas station.
        for i in range(len(gas)):
            # Update the running tank balance after visiting station i.
            total += (gas[i] - cost[i])
            # If the tank runs dry, the current starting station res is invalid.
            if total < 0:
                # Reset running total for the next candidate starting point.
                total = 0
                # Try the next station as the new candidate starting point.
                res = i + 1
        return res

